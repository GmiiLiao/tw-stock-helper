// 每頁收合說明(<PageHelp id>)與帳號選單「📖 使用說明書」共用此檔。
// 結構：這頁做什麼 what → 怎麼操作會得到什麼 how → 怎麼判讀 read → 相關術語 terms。
// 新增頁面時在 PAGE_HELP 加一段即可，兩處自動同步。

// 行級權限標記：字串＝所有人可見；{ premium: true } ＝僅高級會員（含體驗期）顯示。
// 原則（使用者定案）：沒有權限用到的功能，說明也不出現——說明內容與會員權限一致。
export type HelpLine = string | { text: string; premium: true };

export interface PageHelpContent {
  title: string;        // 頁名（與導航一致）
  icon: string;
  premium?: boolean;    // 整頁高級會員限定（非會員導覽隱藏 → 說明書同步隱藏）
  what: string;         // 這頁做什麼（一句話）
  how: HelpLine[];      // 怎麼操作 → 得到什麼
  read: HelpLine[];     // 拿到的資料怎麼判讀
  terms: string[];      // GLOSSARY 的 key
}

// 依權限取可見文字（PageHelp 與 HelpManual 共用）
export function visibleLines(lines: HelpLine[], hasPremium: boolean): string[] {
  return lines
    .filter(l => typeof l === 'string' || hasPremium)
    .map(l => (typeof l === 'string' ? l : l.text));
}

